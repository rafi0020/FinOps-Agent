# One line per completed sale, with money already converted to USD. This is the view most questions need.
ORDER_LINES = """
CREATE VIEW analytics.order_lines AS
SELECT oi.id AS order_item_id, o.id AS order_id, o.order_date, c.id AS customer_id, c.name AS customer_name,
       c.segment, r.name AS region, p.id AS product_id, p.sku, p.name AS product_name, p.category,
       s.name AS supplier, oi.quantity, o.currency, oi.discount_pct,
       round(oi.unit_price * o.fx_rate_to_usd, 4) AS unit_price_usd,
       oi.unit_cost_usd,
       round(oi.quantity * oi.unit_price * o.fx_rate_to_usd * (1 - oi.discount_pct), 2) AS revenue_usd,
       round(oi.quantity * oi.unit_price * o.fx_rate_to_usd * oi.discount_pct, 2) AS discount_usd,
       round(oi.quantity * oi.unit_cost_usd, 2) AS cogs_usd,
       round(oi.quantity * oi.unit_price * o.fx_rate_to_usd * (1 - oi.discount_pct)
             - oi.quantity * oi.unit_cost_usd, 2) AS gross_profit_usd
FROM public.order_items oi
JOIN public.orders o ON o.id = oi.order_id AND o.status = 'completed'
JOIN public.customers c ON c.id = o.customer_id
JOIN public.regions r ON r.id = c.region_id
JOIN public.products p ON p.id = oi.product_id
JOIN public.suppliers s ON s.id = p.supplier_id
"""


def upgrade() -> None:
    for name, columns in TABLES.items():
        op.execute(f"CREATE TABLE {name} ({columns})")
        enable_rls(name)
    for statement in INDEXES:
        op.execute(statement)
    # The views belong to finops_owner. Because row-level security is FORCEd on the tables, it applies to the
    # owner as well, so a query through a view still sees only the organisation set for the transaction.
    # finops_ro is granted these views and nothing in schema public.
    for name in TABLES:
        op.execute(f"""
            CREATE VIEW analytics.{name} AS
            SELECT {_columns_without_org(name)} FROM public.{name}
        """)
    op.execute(ORDER_LINES)


def _columns_without_org(table: str) -> str:
    rows = (
        op.get_bind()
        .exec_driver_sql(
            "SELECT column_name FROM information_schema.columns WHERE table_schema = 'public' "
            "AND table_name = %s AND column_name <> 'org_id' ORDER BY ordinal_position",
            (table,),
        )
        .fetchall()
    )
    return ", ".join(r[0] for r in rows)


